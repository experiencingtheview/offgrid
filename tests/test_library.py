"""Offline library: manifest resolution, download, index, search, confinement."""

import json
import tempfile
import unittest
from pathlib import Path

from offgrid.library import COLLECTIONS, Library, download, sha256_of
from offgrid.semantics import load_lexicon

LISTING = """
<html><body>
<a href="zimgit-water_en_2024-05.zim">old</a>
<a href="zimgit-water_en_2024-08.zim">new</a>
<a href="zimgit-medicine_en_2024-05.zim">other</a>
</body></html>
"""

EMPTY_LISTING = "<html><body><a href=\"unrelated.zim\">x</a></body></html>"


class ResolveTests(unittest.TestCase):
    def test_picks_newest_published_file(self):
        library = Library(root=Path("/tmp/none"), fetch_text=lambda url: LISTING)
        entry = library.entry("water")
        url, filename = library.resolve(entry)
        self.assertEqual(filename, "zimgit-water_en_2024-08.zim")
        self.assertIn("https://download.kiwix.org/zim/other/", url)

    def test_missing_collection_raises_clear_error(self):
        library = Library(root=Path("/tmp/none"), fetch_text=lambda url: EMPTY_LISTING)
        with self.assertRaises(RuntimeError) as ctx:
            library.resolve(library.entry("water"))
        self.assertIn("no file starting with", str(ctx.exception))

    def test_metadata_is_complete(self):
        ids = {entry.id for entry in COLLECTIONS}
        for required in ("water", "medicine", "disaster", "appropedia", "python", "bash", "medicine-wiki"):
            self.assertIn(required, ids)
        for entry in COLLECTIONS:
            self.assertTrue(entry.title and entry.description and entry.license, entry.id)
            self.assertGreater(entry.approx_gb, 0)


class IndexSearchTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        self.library = Library(root=self.root)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel: str, text: str) -> Path:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def test_index_and_stats(self):
        self.write("coding/notes.md", "python list comprehensions are fast")
        self.write("survival/water.txt", "boil water for one minute at sea level")
        data = self.library.index()
        self.assertEqual(len(data["entries"]), 2)
        stats = self.library.stats()
        self.assertEqual(stats["files"], 2)
        self.assertEqual(stats["categories"]["survival"], 1)

    def test_search_finds_text_and_paths(self):
        self.write("survival/water.txt", "To disinfect water, boil for one minute.")
        self.library.index()
        hits = self.library.search("boil water")
        self.assertTrue(hits)
        self.assertTrue(any("water.txt" in hit for hit in hits))

    def test_search_matches_meaning_not_words(self):
        self.write("survival/water.txt", "To disinfect water, boil for one minute.")
        self.library.index()
        hits = self.library.search("how do I make drinking water safe")
        self.assertTrue(hits)
        self.assertTrue(any("water.txt" in hit for hit in hits))

    def test_search_expands_synonyms(self):
        self.write("coding/deploy.md", "Deployment runs scripts/release.sh")
        self.library.index()
        hits = self.library.search("how do I ship this")
        self.assertTrue(hits)
        self.assertTrue(any("deploy.md" in hit for hit in hits))

    def test_project_lexicon_expands_library_synonyms(self):
        path = self.root / "lexicon.json"
        path.write_text(
            json.dumps({"groups": {"billing": ["invoice", "receipt"]}}),
            encoding="utf-8",
        )
        library = Library(root=self.root, lexicon=load_lexicon(path))
        self.write("billing.md", "Invoices are generated by scripts/billing.py")
        library.index()
        hits = library.search("where is the receipt")
        self.assertTrue(any("billing.md" in hit for hit in hits))
        self.assertTrue(any("same idea: billing" in hit for hit in hits))

    def test_search_survives_a_typo(self):
        self.write("coding/notes.md", "The verification command for this project is make check")
        self.library.index()
        hits = self.library.search("verifcation command")
        self.assertTrue(hits)
        self.assertTrue(any("notes.md" in hit for hit in hits))

    def test_search_on_empty_library(self):
        self.assertEqual(self.library.search("anything"), [])

    def test_search_ignores_documents_with_no_matching_term(self):
        self.write("a.txt", "boil water")
        self.library.index()
        self.assertEqual(self.library.search("plutonium reactor"), [])

    def test_search_prefers_documents_matching_more_terms(self):
        self.write("one.txt", "boil water for one minute at sea level")
        self.write("two.txt", "boil")
        self.library.index()
        hits = self.library.search("boil water")
        self.assertTrue(hits)
        self.assertIn("one.txt", hits[0])

    def test_read_numbers_lines_and_confines(self):
        self.write("doc.txt", "first\nsecond\nthird")
        text = self.library.read("doc.txt", offset=2, limit=1)
        self.assertIn("2| second", text)
        self.assertNotIn("first", text)

    def test_read_refuses_escape(self):
        with self.assertRaises(ValueError):
            self.library.read("../outside.txt")

    def test_read_explains_zim_archives(self):
        self.write("coding/python.zim", "binary-ish")
        with self.assertRaises(ValueError) as ctx:
            self.library.read("coding/python.zim")
        self.assertIn("ZIM reader", str(ctx.exception))

    def test_archive_shows_up_in_search_with_note(self):
        self.write("coding/devdocs_en_python_2026-10.zim", "archive")
        self.library.index()
        hits = self.library.search("python")
        self.assertTrue(any("open with Kiwix" in hit for hit in hits))

    def test_verify_reports_dead_collection_without_network(self):
        library = Library(root=self.root, fetch_text=lambda url: EMPTY_LISTING)
        ok, message = library.verify(library.entry("python"))
        self.assertFalse(ok)
        self.assertIn("no file starting with", message)

    def test_index_ignores_partial_downloads(self):
        self.write("coding/x.md#part?", "x")
        (self.root / "coding").mkdir(parents=True, exist_ok=True)
        (self.root / "coding" / "half.zim.part").write_text("partial")
        data = self.library.index()
        self.assertFalse(any(entry["path"].endswith(".part") for entry in data["entries"]))


class DownloadTests(unittest.TestCase):
    def test_download_writes_file_and_hashes(self):
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "source.bin"
            source.write_bytes(b"offgrid" * 1000)
            dest = Path(tmp) / "nested" / "copy.bin"
            download(source.as_uri(), dest)
            self.assertEqual(dest.read_bytes(), source.read_bytes())
            self.assertEqual(len(sha256_of(dest)), 64)

    def test_existing_file_is_not_redownloaded(self):
        with tempfile.TemporaryDirectory() as tmp:
            library = Library(root=Path(tmp), fetch_text=lambda url: LISTING)
            entry = library.entry("water")
            target = library.target_for(entry, "zimgit-water_en_2024-08.zim")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(b"already here")
            self.assertEqual(library.download(entry), target)
            self.assertEqual(target.read_bytes(), b"already here")


if __name__ == "__main__":
    unittest.main()
