"""Long-term memory: storage, dedupe, ranking and provenance."""

import json
import sqlite3
import tempfile
import unittest
from pathlib import Path

from offgrid.memory import MemoryStore, make_key, normalize, tokens


class MemoryTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.path = Path(self.tmp.name) / "memory.db"
        self.memory = MemoryStore(self.path)

    def tearDown(self):
        self.memory.close()
        self.tmp.cleanup()

    def test_remember_and_recall(self):
        new_id = self.memory.remember("The verify command for this project is pytest", kind="repo")
        self.assertIsNotNone(new_id)
        hits = self.memory.recall("verify command project")
        self.assertEqual(len(hits), 1)
        self.assertEqual(hits[0].id, new_id)

    def test_recall_matches_meaning_not_wording(self):
        self.memory.remember("Verification command for this project: `make test` (it passed).", kind="repo")
        hits = self.memory.recall("how do I check that the build works")
        self.assertEqual(len(hits), 1)
        self.assertIn("make test", hits[0].text)
        self.assertIn("same idea", hits[0].reason)

    def test_project_lexicon_teaches_memory_a_new_synonym(self):
        project = Path(self.tmp.name) / ".offgrid"
        project.mkdir(parents=True, exist_ok=True)
        (project / "lexicon.json").write_text(
            json.dumps({"groups": {"billing": ["invoice", "receipt"]}}),
            encoding="utf-8",
        )
        memory = MemoryStore(project / "memory.db")
        self.addCleanup(memory.close)
        self.assertEqual(memory.lexicon_warnings, [])
        memory.remember("Invoices are generated by scripts/billing.py", kind="fact")
        hits = memory.recall("where is the receipt")
        self.assertEqual(len(hits), 1)
        self.assertIn("billing.py", hits[0].text)
        self.assertIn("billing", hits[0].reason)

    def test_recall_expands_synonyms(self):
        self.memory.remember("Deployment runs scripts/release.sh", kind="fact")
        hits = self.memory.recall("how do I ship this")
        self.assertEqual(len(hits), 1)
        self.assertIn("release.sh", hits[0].text)

    def test_pending_notes_are_invisible_to_meaning_search_too(self):
        self.memory.remember("Deployment runs scripts/release.sh", kind="fact", status="pending")
        self.assertEqual(self.memory.recall("how do I ship this"), [])
        self.assertEqual(self.memory.prompt_block("how do I ship this"), "")

    def test_recall_ignores_unrelated_notes(self):
        self.memory.remember("The API base url lives in config/settings.py", kind="fact")
        self.assertEqual(self.memory.recall("quantum chromodynamics"), [])

    def test_duplicate_is_not_stored_twice(self):
        first = self.memory.remember("Tests live in the tests directory", kind="fact")
        second = self.memory.remember("Tests live in the tests directory", kind="fact")
        self.assertIsNotNone(first)
        self.assertIsNone(second)
        self.assertEqual(len(self.memory.all()), 1)
        self.assertEqual(self.memory.all()[0].uses, 2)

    def test_explicit_key_updates_instead_of_duplicating(self):
        self.memory.remember("verify: pytest", kind="repo", key="verify-command", confidence=0.5)
        self.memory.remember("verify: python3 -m pytest -q", kind="repo", key="verify-command", confidence=0.9)
        items = self.memory.all()
        self.assertEqual(len(items), 1)
        self.assertIn("python3 -m pytest", items[0].text)
        self.assertAlmostEqual(items[0].confidence, 0.9)

    def test_filters_by_kind(self):
        self.memory.remember("a warning about flaky tests here", kind="warning")
        self.memory.remember("a plain fact about flaky tests here", kind="fact")
        warnings = self.memory.recall("flaky tests", kinds=("warning",))
        self.assertEqual([item.kind for item in warnings], ["warning"])

    def test_corrections_outrank_plain_facts(self):
        self.memory.remember("database migrations are run with alembic upgrade", kind="fact")
        self.memory.remember("database migrations are run with alembic upgrade head", kind="correction")
        hits = self.memory.recall("database migrations")
        self.assertEqual(hits[0].kind, "correction")

    def test_prompt_block_carries_warning_and_provenance(self):
        self.memory.remember("Use `npm test` to verify", kind="repo", source="run-42", confidence=0.9)
        block = self.memory.prompt_block("verify npm test")
        self.assertIn("Use `npm test` to verify", block)
        self.assertIn("run-42", block)
        self.assertIn("can be stale or wrong", block)

    def test_prompt_block_empty_when_nothing_matches(self):
        self.memory.remember("something about widgets", kind="fact")
        self.assertEqual(self.memory.prompt_block("totally different topic"), "")

    def test_repo_notes_ride_along_without_keyword_match(self):
        self.memory.remember("This project verifies with make test", kind="repo")
        self.memory.remember("unrelated trivia about a television show", kind="fact")
        block = self.memory.prompt_block("add a health endpoint")
        self.assertIn("make test", block)
        self.assertNotIn("television show", block)

    def test_forget(self):
        new_id = self.memory.remember("temporary note about bananas", kind="fact")
        self.assertTrue(self.memory.forget(new_id))
        self.assertFalse(self.memory.forget(new_id))
        self.assertEqual(self.memory.all(), [])

    def test_persists_across_instances(self):
        self.memory.remember("the deploy script is scripts/deploy.sh", kind="fact")
        self.memory.close()
        reopened = MemoryStore(self.path)
        self.addCleanup(reopened.close)
        self.assertEqual(len(reopened.recall("deploy script")), 1)

    def test_rejects_too_short_text(self):
        self.assertIsNone(self.memory.remember("ok"))
        self.assertIsNone(self.memory.remember("   "))

    def test_clamps_confidence_and_kind(self):
        self.memory.remember("confidence out of range note here", kind="nonsense", confidence=4.0)
        item = self.memory.all()[0]
        self.assertEqual(item.kind, "fact")
        self.assertEqual(item.confidence, 1.0)

    def test_stats(self):
        self.memory.remember("one fact about caching layers", kind="fact")
        self.memory.remember("one warning about caching layers", kind="warning")
        stats = self.memory.stats()
        self.assertEqual(stats["total"], 2)
        self.assertEqual(stats["by_kind"]["warning"], 1)

    def test_recent_first_listing(self):
        first = self.memory.remember("earlier note about queues", kind="fact")
        second = self.memory.remember("later note about workers", kind="fact")
        ids = [item.id for item in self.memory.all()]
        self.assertEqual(ids[0], second)
        self.assertIn(first, ids)

    def test_touch_increments_uses(self):
        new_id = self.memory.remember("a note about retries", kind="fact")
        self.memory.touch([new_id])
        self.assertEqual(self.memory.get(new_id).uses, 2)

    # -- the review gate -------------------------------------------------
    def test_pending_notes_influence_nothing(self):
        new_id = self.memory.remember(
            "The staging database password rotates weekly", kind="fact", status="pending"
        )
        self.assertIsNotNone(new_id)
        self.assertEqual(self.memory.all(), [])
        self.assertEqual(self.memory.recall("staging database password"), [])
        self.assertEqual(self.memory.prompt_block("staging database"), "")
        self.assertEqual(self.memory.prompt_block("rotate the password"), "")
        self.assertEqual([item.id for item in self.memory.pending()], [new_id])
        self.assertEqual(self.memory.stats()["pending"], 1)
        self.assertEqual(self.memory.stats()["total"], 0)

    def test_accepting_makes_a_note_usable(self):
        new_id = self.memory.remember("Deploys use scripts/deploy.sh", kind="repo", status="pending")
        self.assertEqual(self.memory.accept([new_id]), 1)
        self.assertIn("scripts/deploy.sh", self.memory.prompt_block("add a health endpoint"))
        self.assertEqual(self.memory.pending(), [])

    def test_rejecting_removes_it_from_memory_but_keeps_a_ledger(self):
        new_id = self.memory.remember("A guess that turned out wrong", kind="lesson", status="pending")
        self.assertEqual(self.memory.reject([new_id]), 1)
        self.assertIsNone(self.memory.get(new_id))
        self.assertEqual(self.memory.recall("guess wrong"), [])
        ledger = self.memory.rejected()
        self.assertEqual(len(ledger), 1)
        self.assertIn("guess", ledger[0].text)
        self.assertEqual(ledger[0].count, 1)

    def test_a_rejected_lesson_is_not_reproposed(self):
        text = "Deployment uses the wrong branch"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.assertEqual(self.memory.reject([new_id]), 1)
        self.assertTrue(self.memory.was_rejected(text))
        self.assertIsNone(self.memory.remember(text, kind="lesson", status="pending"))
        self.assertEqual(self.memory.pending(), [])

    def test_near_identical_rejected_wording_is_blocked(self):
        text = "Always run pytest before the tests"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        self.assertTrue(self.memory.was_rejected("Always run pytest before tests"))
        self.assertIsNone(
            self.memory.remember("Always run pytest before tests", kind="lesson", status="pending")
        )

    def test_semantically_reworded_rejections_are_blocked(self):
        text = "Always run pytest before the tests"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        rewordings = (
            "Execute the test suite before committing.",
            "Run the test suite before you commit.",
            "Verify with pytest first.",
            "Make sure tests pass before committing.",
        )
        for wording in rewordings:
            self.assertTrue(self.memory.was_rejected(wording), wording)
            self.assertIsNone(
                self.memory.remember(wording, kind="lesson", status="pending"), wording
            )
        self.assertEqual(self.memory.pending(), [])

    def test_unrelated_lessons_are_not_blocked_by_semantic_rejection(self):
        text = "Always run pytest before the tests"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        unrelated = (
            "Database migrations are run with alembic upgrade head",
            "Backups live in the backups directory",
            "Test the deployment with the smoke check",
            "Write tests for the slugify helper",
        )
        for wording in unrelated:
            self.assertFalse(self.memory.was_rejected(wording), wording)
            self.assertIsNotNone(
                self.memory.remember(wording, kind="lesson", status="pending"), wording
            )

    def test_forgiving_lifts_a_semantic_rejection(self):
        text = "Always run pytest before the tests"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        wording = "Execute the test suite before committing."
        self.assertTrue(self.memory.was_rejected(wording))
        ledger_id = self.memory.rejected()[0].id
        self.assertEqual(self.memory.forgive([ledger_id]), 1)
        self.assertFalse(self.memory.was_rejected(wording))
        self.assertIsNotNone(
            self.memory.remember(wording, kind="lesson", status="pending")
        )

    def test_an_explicit_add_can_override_a_rejection(self):
        text = "Deployment uses the wrong branch"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        self.assertIsNotNone(self.memory.remember(text, kind="lesson"))
        self.assertEqual(len(self.memory.all()), 1)
        self.assertTrue(self.memory.was_rejected(text))  # the negative record remains

    def test_forgive_removes_only_the_rejection_and_restores_nothing(self):
        active = self.memory.remember("Keep this accepted fact", kind="fact")
        text = "A rejected lesson that may be proposed again"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        ledger_id = self.memory.rejected()[0].id

        self.assertEqual(self.memory.forgive([ledger_id]), 1)
        self.assertEqual(self.memory.rejected(), [])
        self.assertEqual([item.id for item in self.memory.all()], [active])
        self.assertEqual(self.memory.pending(), [])
        self.assertFalse(self.memory.was_rejected(text))

    def test_forgive_is_idempotent(self):
        new_id = self.memory.remember("Another wrong lesson", kind="lesson", status="pending")
        self.memory.reject([new_id])
        ledger_id = self.memory.rejected()[0].id
        self.assertEqual(self.memory.forgive([ledger_id]), 1)
        self.assertEqual(self.memory.forgive([ledger_id]), 0)

    def test_forgive_by_exact_text_removes_only_that_record(self):
        first_text = "Always run pytest before the tests"
        second_text = "Backups live in the backups directory"
        first = self.memory.remember(first_text, kind="lesson", status="pending")
        second = self.memory.remember(second_text, kind="lesson", status="pending")
        self.memory.reject([first, second])

        self.assertEqual(self.memory.forgive_matching(first_text), 1)
        self.assertEqual([item.text for item in self.memory.rejected()], [second_text])
        self.assertFalse(self.memory.was_rejected(first_text))
        self.assertTrue(self.memory.was_rejected(second_text))

    def test_forgive_by_exact_text_ignores_case_and_punctuation(self):
        text = "Always run pytest before the tests"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        self.assertEqual(
            self.memory.forgive_matching("always run pytest before the tests!"), 1
        )
        self.assertEqual(self.memory.rejected(), [])

    def test_forgive_by_search_query_lifts_semantic_matches(self):
        text = "Always run pytest before the tests"
        other = "Backups live in the backups directory"
        first = self.memory.remember(text, kind="lesson", status="pending")
        second = self.memory.remember(other, kind="lesson", status="pending")
        self.memory.reject([first, second])

        self.assertEqual(self.memory.forgive_matching("test suite before commit"), 1)
        self.assertEqual([item.text for item in self.memory.rejected()], [other])
        self.assertFalse(
            self.memory.was_rejected("Execute the test suite before committing.")
        )

    def test_forgive_by_query_does_not_touch_unrelated_records(self):
        text = "Backups live in the backups directory"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        self.assertEqual(self.memory.forgive_matching("quantum chromodynamics"), 0)
        self.assertEqual([item.text for item in self.memory.rejected()], [text])

    def test_rejection_ledger_persists(self):
        text = "A rejected lesson about migrations"
        new_id = self.memory.remember(text, kind="lesson", status="pending")
        self.memory.reject([new_id])
        self.memory.close()
        reopened = MemoryStore(self.path)
        self.addCleanup(reopened.close)
        self.assertEqual([item.text for item in reopened.rejected()], [text])
        self.assertEqual(reopened.stats()["rejected"], 1)
        self.assertIsNone(reopened.remember(text, kind="lesson", status="pending"))

    def test_editing_accepts_the_corrected_wording(self):
        new_id = self.memory.remember("Deploy is run by hand", kind="lesson", status="pending")
        item = self.memory.edit(new_id, "Deploy runs scripts/deploy.sh, not by hand")
        self.assertIsNotNone(item)
        self.assertEqual(item.status, "accepted")
        self.assertIn("scripts/deploy.sh", item.text)
        self.assertEqual(self.memory.accept([new_id]), 0)  # already accepted

    def test_editing_rejects_empty_text(self):
        new_id = self.memory.remember("A lesson worth keeping", kind="lesson", status="pending")
        self.assertIsNone(self.memory.edit(new_id, "   "))
        self.assertEqual(self.memory.get(new_id).status, "pending")

    # -- verification evidence on council lessons ------------------------
    def test_council_evidence_is_stored_and_shown(self):
        new_id = self.memory.remember(
            'Council answer to "which flag?", later confirmed by verification: use --jinja',
            kind="lesson",
            source="council: peer",
            status="pending",
            verify_command="python3 -m pytest -q",
            verify_output="1 passed in 0.02s",
        )
        item = self.memory.get(new_id)
        self.assertEqual(item.verify_command, "python3 -m pytest -q")
        self.assertEqual(item.verify_output, "1 passed in 0.02s")
        lines = item.evidence_lines()
        self.assertTrue(any("python3 -m pytest -q" in line for line in lines))
        self.assertTrue(any("1 passed in 0.02s" in line for line in lines))

    def test_evidence_is_only_shown_for_council_lessons(self):
        new_id = self.memory.remember(
            "A deterministic note about this repository",
            kind="repo",
            verify_command="make test",
            verify_output="ok",
        )
        item = self.memory.get(new_id)
        self.assertEqual(item.verify_command, "make test")
        self.assertEqual(item.evidence_lines(), [])

    def test_long_evidence_is_capped_for_storage_and_display(self):
        new_id = self.memory.remember(
            'Council answer to "how?", later confirmed by verification: something durable',
            kind="lesson",
            source="council: peer",
            status="pending",
            verify_command="make test",
            verify_output="x" * 5000,
        )
        item = self.memory.get(new_id)
        self.assertLessEqual(len(item.verify_output), 2000)
        shown = "\n".join(item.evidence_lines())
        self.assertIn("truncated", shown)
        self.assertLess(len(shown), 1000)

    def test_repeated_council_lesson_refreshes_its_evidence(self):
        text = 'Council answer to "how?", later confirmed by verification: use the flag'
        first = self.memory.remember(text, kind="lesson", source="council: peer", status="pending")
        self.memory.remember(
            text,
            kind="lesson",
            source="council: peer",
            status="pending",
            verify_command="make test",
            verify_output="2 passed",
        )
        item = self.memory.get(first)
        self.assertEqual(item.verify_command, "make test")
        self.assertEqual(item.verify_output, "2 passed")

    def test_evidence_is_not_wiped_by_a_rerun_without_it(self):
        text = 'Council answer to "how?", later confirmed by verification: keep the flag'
        first = self.memory.remember(
            text,
            kind="lesson",
            source="council: peer",
            status="pending",
            verify_command="make test",
            verify_output="2 passed",
        )
        self.memory.remember(text, kind="lesson", source="council: peer", status="pending")
        item = self.memory.get(first)
        self.assertEqual(item.verify_command, "make test")
        self.assertEqual(item.verify_output, "2 passed")

    def test_a_repeated_pending_lesson_stays_pending(self):
        self.memory.remember("Tests live in tests/", kind="fact", status="pending")
        self.memory.remember("Tests live in tests/", kind="fact", status="pending")
        self.assertEqual(len(self.memory.pending()), 1)
        self.assertEqual(self.memory.all(), [])

    def test_an_explicit_remember_accepts_an_existing_pending_note(self):
        new_id = self.memory.remember("Tests live in tests/", kind="fact", status="pending")
        self.memory.remember("Tests live in tests/", kind="fact")
        self.assertEqual(self.memory.get(new_id).status, "accepted")

    def test_old_databases_keep_their_notes_accepted(self):
        legacy = Path(self.tmp.name) / "legacy.db"
        db = sqlite3.connect(str(legacy))
        db.execute(
            "CREATE TABLE memories (id INTEGER PRIMARY KEY AUTOINCREMENT, kind TEXT NOT NULL, "
            "text TEXT NOT NULL, key TEXT UNIQUE, source TEXT DEFAULT '', confidence REAL DEFAULT 0.6, "
            "created REAL NOT NULL, uses INTEGER DEFAULT 0)"
        )
        db.execute(
            "INSERT INTO memories (kind, text, key, created, uses) VALUES ('fact', 'older note about cmake', 'k', 1, 1)"
        )
        db.commit()
        db.close()

        migrated = MemoryStore(legacy)
        self.addCleanup(migrated.close)
        self.assertEqual([item.text for item in migrated.all()], ["older note about cmake"])
        self.assertEqual(migrated.pending(), [])
        legacy_item = migrated.all()[0]
        self.assertEqual(legacy_item.verify_command, "")
        self.assertEqual(legacy_item.evidence_lines(), [])

    def test_helpers(self):
        self.assertIn("deploy", tokens("Deploy the service, now"))
        self.assertEqual(normalize("  Hello,   World! "), "hello world")
        self.assertEqual(make_key("fact", "A  b"), make_key("fact", "a b"))
        self.assertNotEqual(make_key("fact", "a b"), make_key("lesson", "a b"))


if __name__ == "__main__":
    unittest.main()
